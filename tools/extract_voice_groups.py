#!/usr/bin/env python3
"""Turn Blob_a5710_a8cdc (the sound engine's voice groups) into assembly.

Writes sound/voice_groups.s with one `voice` line per 12-byte instrument,
labels at every voice group, the keysplit table and the five programmable
waves, and every pointer written
as a symbol, so the data moves correctly when the ROM is shifted. Then
replaces the raw voice-group addresses in sound/tracks/*.s with the labels
and removes the blob from src/data/audio.c, database.json and the build.

Run once from the repo root with a matching build (mf_us.elf) present.
"""
import bisect
import json
import re
import struct
import subprocess
from pathlib import Path

START, END = 0xA5710, 0xA8CDC
VOICES_END = 0xA8C44            # 1143 voices of 12 bytes
KEYSPLIT, KEYSPLIT_END = 0xA8C44, 0xA8C8C
KEYSPLIT_FIRST_KEY = 36         # the keysplit voice points this far before the data
WAVES = range(0xA8C8C, END, 16) # programmable-wave samples, 16 bytes each
SPLIT = VOICES_END
BLOB = "Blob_a5710_a8cdc.bin"
rom = Path("mf_us_baserom.gba").read_bytes()
rom_end = len(rom.rstrip(b"\xff"))

# symbols from the matching build (blob excluded; we are replacing it)
nm = subprocess.run(["arm-none-eabi-nm", "-n", "mf_us.elf"], capture_output=True, text=True, check=True).stdout
syms = []
for l in nm.splitlines():
    p = l.split()
    if len(p) == 3 and p[0].startswith("08") and not p[2].startswith(("$", "_0", "sBlob_a5710")):
        syms.append((int(p[0], 16) & 0xFFFFFF, p[2], p[1]))
syms.sort()
addrs = [a for a, _, _ in syms]

# voice groups referenced by tracks
track_files = sorted(Path("sound/tracks").glob("*.s"))
group_starts = set()
for f in track_files:
    for m in re.findall(r"\.word 0x(80a[5-8][0-9a-f]{3})\b", f.read_text()):
        a = int(m, 16) & 0xFFFFFF
        if START <= a < SPLIT:
            group_starts.add(a)

entries = []
o = START
while o < SPLIT:
    entries.append((o,) + struct.unpack_from("<BBBBIBBBB", rom, o))
    o += 12
split_tables = set()
for o, t, key, ln, pan, ptr, a, d, s, r in entries:
    if t in (0x40, 0x80) and START <= (ptr & 0xFFFFFF) < SPLIT:
        group_starts.add(ptr & 0xFFFFFF)
    if t == 0x40:
        split_tables.add(struct.unpack_from("<I", rom, o + 8)[0] & 0xFFFFFF)


def label(addr):
    if addr in WAVES:
        return f"gWaveData_{addr:x}"
    return f"gVoiceGroup_{addr:x}"


KEYSPLIT_LABEL = f"gKeySplitTable_{KEYSPLIT:x}"


def pointer(word):
    """Symbolic expression for a ROM pointer, else None."""
    if not (0x08000000 <= word < 0x08000000 + rom_end):
        return None
    a = word & 0xFFFFFF
    if START <= a < END:
        if a in group_starts or a in WAVES:
            return label(a)
        if a == KEYSPLIT - KEYSPLIT_FIRST_KEY:
            return f"{KEYSPLIT_LABEL} - {KEYSPLIT_FIRST_KEY}"
        return None
    i = bisect.bisect_right(addrs, a) - 1
    if i < 0:
        return None
    base, name, kind = syms[i]
    if kind.islower():
        return None  # file-local symbol: can't be referenced from here
    return name if a == base else f"{name} + 0x{a - base:x}"


out = [
    "@ Voice groups (instrument tables) for the sound engine.",
    "@ Generated by tools/extract_voice_groups.py from the US ROM layout.",
    "@ voice: type, key, length, pan/sweep, sample-or-group, attack, decay, sustain, release",
    "@ voice_keysplit: type, key, length, pan, voice group, keysplit table",
    "",
    "    .macro voice type:req, key:req, len:req, pan:req, ptr:req, atk:req, dec:req, sus:req, rel:req",
    "    .byte \\type, \\key, \\len, \\pan",
    "    .4byte \\ptr",
    "    .byte \\atk, \\dec, \\sus, \\rel",
    "    .endm",
    "",
    "    .macro voice_keysplit type:req, key:req, len:req, pan:req, group:req, table:req",
    "    .byte \\type, \\key, \\len, \\pan",
    "    .4byte \\group",
    "    .4byte \\table",
    "    .endm",
    "",
    "    .section .rodata",
    "    .align 2, 0",
    "",
]
unresolved = 0
for o, t, key, ln, pan, ptr, a, d, s, r in entries:
    if o in group_starts:
        out += ["", f"    .global {label(o)}", f"{label(o)}:"]
    pexpr = pointer(ptr)
    if t == 0x40:
        table = struct.unpack_from("<I", rom, o + 8)[0]
        texpr = pointer(table)
        if pexpr and texpr:
            out.append(f"    voice_keysplit 0x{t:02x}, {key}, {ln}, {pan}, {pexpr}, {texpr}")
            continue
    if pexpr is None:
        if 0x08000000 <= ptr < 0x08000000 + rom_end and (t & 7) in (0, 3) and t < 0x40:
            unresolved += 1
        pexpr = f"0x{ptr:08x}"
    out.append(f"    voice 0x{t:02x}, {key}, {ln}, {pan}, {pexpr}, {a}, {d}, {s}, {r}")

out += ["", "@ Keysplit table: voice index per note, starting at note 36", f"    .global {KEYSPLIT_LABEL}", f"{KEYSPLIT_LABEL}:"]
ks = rom[KEYSPLIT:KEYSPLIT_END]
for i in range(0, len(ks), 12):
    out.append("    .byte " + ", ".join(str(b) for b in ks[i:i + 12]))
out += ["", "@ Programmable-wave samples (32 4-bit steps each)"]
for w in WAVES:
    out += [f"    .global {label(w)}", f"{label(w)}:", "    .byte " + ", ".join(f"0x{b:02x}" for b in rom[w:w + 16])]
Path("sound/voice_groups.s").write_text("\n".join(out) + "\n")
print(f"{len(entries)} voices, {len(group_starts)} voice groups, {unresolved} unresolved sample pointers")

# tracks: raw voice group addresses -> labels
n = 0
for f in track_files:
    text = f.read_text()

    def sub(m):
        global n
        a = int(m.group(1), 16) & 0xFFFFFF
        if a in group_starts:
            n += 1
            return f".word {label(a)}"
        return m.group(0)

    new = re.sub(r"\.word 0x(80a[5-8][0-9a-f]{3})\b", sub, text)
    if new != text:
        f.write_text(new)
print(f"{n} track references now use labels")

# remove the blob
c = Path("src/data/audio.c")
ct = c.read_text()
old = f'static const u8 sBlob_a5710_a8cdc[] = INCBIN_U8("data/{BLOB}");'
assert old in ct
c.write_text(ct.replace(old, "// The voice groups that followed here are in sound/voice_groups.s").rstrip() + "\n")
db = json.loads(Path("database.json").read_text())
db = [e for e in db if e["path"] != BLOB]
Path("database.json").write_text(json.dumps(db, indent=2) + "\n")
ld = Path("linker.ld")
lt = ld.read_text()
anchor = "        src/data/audio.o(.rodata);\n"
assert anchor in lt
ld.write_text(lt.replace(anchor, anchor + "        sound/voice_groups.o(.rodata);\n", 1))
